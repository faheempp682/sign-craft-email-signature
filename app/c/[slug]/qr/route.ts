import QRCode from "qrcode";
import { cardUrl } from "@/lib/cards/signature-link";
import { fetchPublicCard, siteOrigin } from "@/lib/cards/public";
import { clientKey, hit } from "@/lib/cards/rate-limit";

/** Public. A QR code of the card's own address, as SVG (default) or PNG (?format=png&size=512). Only for published cards. */
export const dynamic = "force-dynamic";

const text = (status: number, body: string, headers: Record<string, string> = {}) =>
  new Response(body, { status, headers: { "Content-Type": "text/plain; charset=utf-8", "X-Content-Type-Options": "nosniff", ...headers } });

export async function GET(req: Request, { params }: { params: Promise<{ slug: string }> }) {
  const limit = hit(`qr:${clientKey(req)}`, 60, 60_000);
  if (!limit.allowed) return text(429, "Too many requests", { "Retry-After": String(limit.retryAfter), "Cache-Control": "no-store" });

  const { slug } = await params;
  const card = await fetchPublicCard(slug);
  if (!card) return text(404, "Not found", { "Cache-Control": "public, max-age=30" });

  const target = cardUrl(card.slug, siteOrigin(req.headers));
  if (!target) return text(404, "Not found", { "Cache-Control": "public, max-age=30" });

  const q = new URL(req.url).searchParams;
  const png = q.get("format") === "png";
  const download = q.get("download") === "1";
  const size = Math.min(1024, Math.max(128, Number.parseInt(q.get("size") ?? "512", 10) || 512));
  const headers: Record<string, string> = {
    "Cache-Control": "public, max-age=3600, s-maxage=3600",
    "X-Content-Type-Options": "nosniff",
  };
  if (download) headers["Content-Disposition"] = `attachment; filename="${card.slug}-qr.${png ? "png" : "svg"}"`;

  if (png) {
    const buf = await QRCode.toBuffer(target, { type: "png", width: size, margin: 2, errorCorrectionLevel: "M" });
    return new Response(new Uint8Array(buf), { status: 200, headers: { ...headers, "Content-Type": "image/png" } });
  }
  const svg = await QRCode.toString(target, { type: "svg", margin: 2, errorCorrectionLevel: "M" });
  // An SVG opened on its own could carry script; this one is generated by the library, and the CSP makes that explicit.
  return new Response(svg, { status: 200, headers: { ...headers, "Content-Type": "image/svg+xml; charset=utf-8", "Content-Security-Policy": "default-src 'none'; style-src 'unsafe-inline'" } });
}
